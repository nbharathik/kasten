/// The colour of a preset name; black for one this table does not have.
pub fn preset(name: &str) -> Option<Rgb> {
    let value = NAMES
        .iter()
        .find(|(n, _)| *n == name)
        .map_or(0x000000, |(_, v)| *v);
    Some(Rgb((value >> 16) as u8, (value >> 8) as u8, value as u8))
}
